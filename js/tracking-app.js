var app = new Vue({
    el: '#app',
    data: {
        pengirimanList: baseData.pengirimanList,
        paketList: baseData.paket,
        trackingData: baseData.tracking,

        searchNoDO: '',
        currentTracking: null,
        errorTracking: '',

        newDO: {
            nim: '',
            nama: '',
            ekspedisi: '',
            selectedPaket: '',
            tanggalKirim: new Date().toISOString().slice(0, 10)
        },
        selectedPaketDetail: null,
        formDOError: '',
        formDOSuccess: ''
    },
    computed: {
        // Otomatis men-generate nomor DO dengan tahun 2026 dan increment sequence (0002, 0003, dst)
        autoGeneratedNoDO: function() {
            var keys = Object.keys(this.trackingData);
            var nextNum = keys.length + 1;
            var paddedNum = String(nextNum).padStart(4, '0');
            return "DO2026-" + paddedNum;
        }
    },
    watch: {
        searchNoDO: function(val) {
            if (!val) {
                this.currentTracking = null;
                this.errorTracking = '';
            }
        }
    },
    methods: {
        lacakDO: function() {
            var resi = this.searchNoDO.trim();
            if (this.trackingData[resi]) {
                this.currentTracking = this.trackingData[resi];
                this.errorTracking = '';
            } else {
                this.currentTracking = null;
                this.errorTracking = "Nomor DO '" + resi + "' tidak ditemukan dalam sistem.";
            }
        },
        onPaketChange: function() {
            var kodePaket = this.newDO.selectedPaket;
            var found = this.paketList.find(function(p) {
                return p.kode === kodePaket;
            });
            this.selectedPaketDetail = found || null;
        },
        submitDO: function() {
            if (!this.newDO.nim || !this.newDO.nama || !this.newDO.ekspedisi || !this.newDO.selectedPaket) {
                this.formDOError = "Harap isi seluruh field formulir DO dengan benar!";
                this.formDOSuccess = '';
                return;
            }
            this.formDOError = '';

            var newNoDO = this.autoGeneratedNoDO;
            var paketObj = this.selectedPaketDetail;

            // Simpan ke object tracking agar otomatis merubah sequence number berikutnya
            Vue.set(this.trackingData, newNoDO, {
                nim: this.newDO.nim,
                nama: this.newDO.nama,
                status: "Diproses di Gudang UT",
                ekspedisi: this.newDO.ekspedisi,
                tanggalKirim: this.newDO.tanggalKirim,
                paket: paketObj.kode,
                total: paketObj.harga,
                perjalanan: [
                    { waktu: this.newDO.tanggalKirim + " 08:00:00", keterangan: "Delivery Order berhasil dibuat dan divalidasi sistem." }
                ]
            });

            this.formDOSuccess = "Berhasil membuat Delivery Order baru dengan nomor: " + newNoDO;
            
            // Reset form
            this.newDO.nim = '';
            this.newDO.nama = '';
            this.newDO.ekspedisi = '';
            this.newDO.selectedPaket = '';
            this.selectedPaketDetail = null;
        }
    }
});